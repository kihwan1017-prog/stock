def curated_krx_holidays_for_years(
    years: list[int],
) -> dict[date, str]:
    """연도 목록에 대한 휴장일 맵."""

    out: dict[date, str] = {}
    for year in years:
        for d, name in _KRX_HOLIDAYS.get(year, []):
            out[d] = name
    return out


def curated_year_coverage() -> tuple[int, int]:
    years = sorted(_KRX_HOLIDAYS.keys())
    return years[0], years[-1]
